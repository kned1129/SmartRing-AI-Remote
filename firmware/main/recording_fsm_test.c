#include <assert.h>
#include <stdio.h>
#include "recording_fsm.h"
void recording_fsm_selftest(void){
 rec_state_t s=REC_IDLE;unsigned checks=0;
 #define STEP(event,expected) do{s=rec_transition(s,event);assert(s==expected);checks++;}while(0)
 STEP(REC_START,REC_STARTING);STEP(REC_START,REC_STARTING);
 STEP(REC_STOP,REC_STOPPING);STEP(REC_ACK_RECORDING,REC_STOPPING);
 STEP(REC_STOP,REC_STOPPING);STEP(REC_ACK_PROCESSING,REC_PROCESSING);
 STEP(REC_START,REC_PROCESSING);STEP(REC_ACK_IDLE,REC_COMPLETED);
 STEP(REC_START,REC_STARTING);STEP(REC_ACK_RECORDING,REC_RECORDING);
 STEP(REC_CANCEL,REC_CANCELLED);STEP(REC_ACK_RECORDING,REC_CANCELLED);
 STEP(REC_ACK_IDLE,REC_CANCELLED);STEP(REC_START,REC_STARTING);
 STEP(REC_DISCONNECT,REC_FAILED);STEP(REC_ACK_RECORDING,REC_FAILED);
 STEP(REC_ACK_IDLE,REC_FAILED);STEP(REC_START,REC_STARTING);
 STEP(REC_CANCEL,REC_CANCELLED);STEP(REC_ACK_PROCESSING,REC_CANCELLED);
 STEP(REC_START,REC_STARTING);STEP(REC_ACK_RECORDING,REC_RECORDING);
 STEP(REC_ERROR,REC_FAILED);STEP(REC_STOP,REC_FAILED);
 for(int state=REC_IDLE;state<=REC_CANCELLED;state++){
  s=(rec_state_t)state;STEP(REC_CANCEL,REC_CANCELLED);
 }
 printf("RECORD_FSM_SELFTEST checks=%u PASS\n",checks);
 #undef STEP
}
